// The coaching-style row on Create Manager: tapping a style in view leaves the row where it is; picking a real
// manager whose style is far along the row brings it into view. node scripts/qa/style-row.mjs   (needs the dev server)
import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })).newPage()
await page.goto('http://localhost:5173/')
await page.getByText('New Career').first().click()
await page.waitForSelector('.nc-styles', { timeout: 30000 })
const pos = () => page.evaluate(() => document.querySelector('.nc-styles').scrollLeft)
const seen = () => page.evaluate(() => { const r = document.querySelector('.nc-styles'), e = r.querySelector('.nc-style.on'); const a = e.getBoundingClientRect(), b = r.getBoundingClientRect(); return a.left >= b.left && a.right <= b.right })
const before = await pos()
await page.locator('.nc-style').nth(1).click()
await page.waitForTimeout(600)
console.log(`tapping the second style: row ${before} -> ${await pos()} (${before === (await pos()) ? 'OK, stays' : 'MOVED'})`)
await page.locator('.seg button', { hasText: 'Real manager' }).click()
await page.waitForTimeout(400)
// a real manager who plays Park the Bus (the last style)
const i = await page.evaluate(() => [...document.querySelectorAll('.nc-reals .li')].findIndex((li) => /Park the Bus/.test(li.textContent)))
await page.locator('.nc-reals .li').nth(i).click()
await page.waitForTimeout(800)
console.log(`real manager with the last style: ${(await seen()) ? 'OK, in view' : 'NOT IN VIEW'} (row at ${await pos()})`)
await browser.close()
