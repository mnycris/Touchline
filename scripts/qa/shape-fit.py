"""Fits each formation's residual bias (scripts/qa/lab/formation-split.ts runs, one file per club) into the table in
src/engine/match/shapeData.ts: a log-multiplier on the chances a shape creates and on the chances it allows, chosen so
that with the same players no shape is worth more than another in xG difference, while each keeps how open it is (an
attacking shape still makes and allows more than a holding one).

  python3 scripts/qa/shape-fit.py [--shrink 1] [--prev src/engine/match/shapeData.ts] runs/*.txt > src/engine/match/shapeData.ts

With --prev, the measured runs were played with that table already in force, and the new one is fitted on top of it.
"""
import sys, json, re, math, statistics as st

args = sys.argv[1:]
shrink, prev = 1.0, {}
files = []
i = 0
while i < len(args):
    if args[i] == '--shrink':
        shrink = float(args[i + 1]); i += 2
    elif args[i] == '--prev':
        for m in re.finditer(r"'([^']+)': \[ *(-?[\d.]+), *(-?[\d.]+) *\]", open(args[i + 1]).read()):
            prev[m.group(1)] = (float(m.group(2)), float(m.group(3)))
        i += 2
    else:
        files.append(args[i]); i += 1

clubs = []
for f in files:
    for line in open(f):
        if line.startswith('JSON '):
            clubs.append(json.loads(line[5:]))
if not clubs:
    sys.exit('no runs')
forms = list(clubs[0]['out'].keys())
level_f = st.mean(st.mean(c['out'][f]['xf'] for f in forms) for c in clubs)
level_a = st.mean(st.mean(c['out'][f]['xa'] for f in forms) for c in clubs)
rows = []
for f in forms:
    ef = st.mean(c['out'][f]['xf'] - st.mean(c['out'][g]['xf'] for g in forms) for c in clubs)
    ea = st.mean(c['out'][f]['xa'] - st.mean(c['out'][g]['xa'] for g in forms) for c in clubs)
    open_ = (ef + ea) / 2
    tf, ta = ef + shrink * (open_ - ef), ea + shrink * (open_ - ea)
    a = math.log((level_f + tf) / (level_f + ef))
    d = math.log((level_a + ta) / (level_a + ea))
    pa, pd = prev.get(f, (0.0, 0.0))
    rows.append((f, round(pa + a, 3), round(pd + d, 3), ef - ea))
names = sorted(set(c['club'] for c in clubs))
n = len(clubs)
print("// Generated by scripts/qa/shape-fit.py from scripts/qa/lab/formation-split.ts runs (" + f"{n} runs, {len(names)} clubs: {', '.join(names)}" + ").")
print("// Do not edit by hand: re-run the fit after changing the engine. Each pair is the log-multiplier on the chances a")
print("// side in that shape creates and on the chances it allows: the bias the shape's own geometry leaves once the")
print("// players and their roles have done what they do, taken out so that no shape is worth more than another with the")
print("// same players, while each keeps how open it is.")
print("export const SHAPE_FX: Record<string, [number, number]> = {")
for f, a, d, _ in rows:
    print(f"  '{f}': [{a}, {d}],")
print("}")
sys.stderr.write(f"level for {level_f:.2f} against {level_a:.2f}; measured xGD bias sd {math.sqrt(sum(r[3] ** 2 for r in rows) / len(rows)):.3f}\n")
