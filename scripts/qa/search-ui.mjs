// Universal search and Following, as a manager would use them: open search from the top bar (the field must have
// focus straight away), type, filter, open results, follow things, then the Following feed in the news.
// node scripts/qa/search-ui.mjs <save> [outDir]   (dev server on :5173)
import fs from 'node:fs'
import { openSave } from './load-save.mjs'
const [file, OUT = '/tmp/opus-search'] = process.argv.slice(2)
fs.mkdirSync(OUT, { recursive: true })
const { page, browser, errors } = await openSave(file)
let n = 0
const shot = async (name, wait = 420) => { await page.waitForTimeout(wait); await page.screenshot({ path: `${OUT}/${String(++n).padStart(2, '0')}-${name}.png` }) }
const js = (fn, arg) => page.evaluate(fn, arg)
const log = (...a) => console.log(...a)
const searchBtn = () => page.locator('.topbar .search-btn').last()
const type = async (q) => { await page.fill('.spot-input', ''); await page.type('.spot-input', q, { delay: 35 }) }

await page.waitForTimeout(2200) // index warms in idle time
await shot('central-topbar', 200)
await searchBtn().click()
log('focused after tap:', await js(() => document.activeElement?.className))
await shot('open-mid', 90)
await shot('open-empty', 400)
await type('saka')
await shot('saka', 500)
await type('bruno g')
await shot('bruno-g', 450)
await type('spurs')
await shot('spurs', 450)
await type('mbape')
await shot('mbape-typo', 450)
await type('man')
await shot('man', 450)
await page.locator('.spot-cats .chip', { hasText: 'Clubs' }).click()
await shot('man-clubs', 350)
await type('contracts')
await shot('career', 400)
await type('zzqx')
await shot('nothing', 400)
// open a player from the results and follow him
await type('gyokeres')
await page.waitForTimeout(400)
const t0 = Date.now()
await page.locator('.spot-top-main, .spot-row').first().click()
await shot('player-opened', 450)
log('search closed:', await js(() => !window.__game.getState().searchOpen), 'route:', JSON.stringify(await js(() => { const s = window.__game.getState(); return s.stacks[s.tab].at(-1) })), Date.now() - t0, 'ms')
await page.locator('.topbar .follow-btn').first().click()
await shot('player-followed', 500)
// back, and the search comes back as it was
await searchBtn().click()
await shot('reopen-kept', 420)
log('kept query:', await js(() => document.querySelector('.spot-input')?.value))
// a manager, a club and a competition, followed from search and their pages
await type('arteta')
await page.waitForTimeout(400)
await page.locator('.spot-top-main, .spot-row').first().click()
await shot('coach', 600)
await page.locator('.topbar .follow-btn').first().click()
await page.waitForTimeout(300)
await js(() => { const s = [...document.querySelectorAll('.screen')].pop(); if (s) s.scrollTop = 600 })
await shot('coach-2', 300)
await searchBtn().click()
await type('chelsea')
await page.waitForTimeout(400)
// follow straight from the top hit
await page.locator('.spot-top .follow-btn').click()
await shot('top-hit-follow', 450)
await page.locator('.spot-top-main').click()
await shot('club', 600)
await searchBtn().click()
await type('premier league')
await page.waitForTimeout(400)
await page.locator('.spot-top-main').click()
await shot('comp', 600)
await page.locator('.topbar .follow-btn').first().click()
await page.waitForTimeout(300)
// a transfer story
const sid = await js(() => { const w = window.__game.getState().world; return (w.market?.stories || []).find((s) => s.stage === 'negotiating' || s.stage === 'close')?.id })
if (sid) { await js((id) => window.__game.getState().go({ name: 'story', params: { id } }), sid); await page.waitForTimeout(500); await page.locator('.topbar .follow-btn').first().click(); await shot('story-followed', 450) }
// empty search: following strip + recents
await searchBtn().click()
await page.locator('.spot-cancel').click()
await page.waitForTimeout(350)
await searchBtn().click()
await shot('home-following-recent', 450)
await page.locator('.spot-cancel').click()
await shot('dismissed', 360)
// the news, Following
await js(() => window.__game.getState().go({ name: 'news' }))
await page.waitForTimeout(500)
await page.locator('.chips .chip', { hasText: 'Following' }).click()
await shot('news-following', 600)
await js(() => { const s = [...document.querySelectorAll('.screen')].pop(); if (s) s.scrollTop = 700 })
await shot('news-following-2', 300)
await page.locator('.link', { hasText: 'Manage' }).click()
await shot('manage', 500)
log('follows:', JSON.stringify(await js(() => window.__game.getState().world.follows)))
console.log(JSON.stringify({ errors }))
await browser.close()
